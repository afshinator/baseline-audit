#!/usr/bin/env node
// Rebuild data/mappings.json from e18e's module-replacements manifest, enriched with
// data/overrides.json (hand-maintained keep-signals, polyfill costs, notes).
//
//   node scripts/sync-mappings.mjs                 # fetch latest from npm
//   node scripts/sync-mappings.mjs --from <dir>    # use an extracted module-replacements package
//
// Rows that come only from e18e are marked usage_analyzed:false and can never be
// reported as a clean swap, because nobody has checked their keep-signals here.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const OUT = path.join(ROOT, 'data', 'mappings.json');
const OVERRIDES = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'overrides.json'), 'utf8')).packages;
const FEATURES = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'web-features.json'), 'utf8')).features;
const MANIFESTS = ['native.json', 'preferred.json'];

const DRY = process.argv.includes('--dry-run');
const fromIdx = process.argv.indexOf('--from');
let pkgDir;
if (fromIdx > -1) {
  pkgDir = path.resolve(process.argv[fromIdx + 1]);
} else {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sym-mr-'));
  const spec = execFileSync('npm', ['view', 'module-replacements', 'dist-tags.latest'], { encoding: 'utf8' }).trim();
  execFileSync('npm', ['pack', `module-replacements@${spec}`, '--silent'], { cwd: tmp, stdio: 'ignore' });
  const tgz = fs.readdirSync(tmp).find(f => f.endsWith('.tgz'));
  execFileSync('tar', ['xzf', tgz, '-C', tmp], { cwd: tmp });
  pkgDir = path.join(tmp, 'package');
}
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));

const rows = new Map();
const unresolvedFeatures = new Set();
let considered = 0;

for (const name of MANIFESTS) {
  const m = JSON.parse(fs.readFileSync(path.join(pkgDir, 'manifests', name), 'utf8'));
  const replacements = m.replacements ?? {};
  for (const [moduleName, ref] of Object.entries(m.mappings ?? {})) {
    considered++;
    const ids = (ref?.replacements ?? []).filter(id => replacements[id]?.webFeatureId?.featureId);
    if (!ids.length) continue;
    const target = replacements[ids[0]];
    const featureId = target.webFeatureId.featureId;
    if (!FEATURES[featureId]) { unresolvedFeatures.add(`${featureId} (${moduleName})`); continue; }
    const over = OVERRIDES[moduleName];
    // A curated override wins over the manifest wording: it was written against real usage.
    const featureIds = over?.feature_ids?.length ? over.feature_ids.filter(f => FEATURES[f]) : [featureId];
    if (!featureIds.length) continue;
    rows.set(moduleName, {
      package: moduleName,
      cluster: over?.cluster ?? (name === 'native.json' ? 'platform' : 'preferred'),
      replacement: over?.replacement ?? (target.description || target.id || ids[0]),
      feature_ids: featureIds,
      keep_if: over?.keep_if ?? [],
      usage_analyzed: Boolean(over),
      ...(over?.polyfill ? { polyfill: over.polyfill } : {}),
      ...(over?.partial ? { partial: true } : {}),
      note: over?.note ?? `From e18e/${path.basename(name, '.json')}; no usage analysis in this repo yet, so verify how you call it before swapping.`,
      source: over ? 'curated+e18e' : 'e18e',
    });
  }
}
// Curated rows the manifest does not cover survive: they carry knowledge the manifest lacks.
for (const [name, over] of Object.entries(OVERRIDES)) {
  if (rows.has(name)) continue;
  if (over.feature_ids?.length && !over.feature_ids.some(f => FEATURES[f])) continue;
  rows.set(name, {
    package: name,
    cluster: over.cluster ?? 'misc',
    replacement: over.replacement,
    feature_ids: over.feature_ids ?? [],
    keep_if: over.keep_if ?? [],
    usage_analyzed: true,
    ...(over.polyfill ? { polyfill: over.polyfill } : {}),
    ...(over.partial ? { partial: true } : {}),
    note: over.note ?? '',
    source: 'curated',
  });
}

const out = {
  schema: 2,
  upstream: { name: 'e18e/module-replacements', version: pkg.version },
  synced_at: new Date().toISOString().slice(0, 10),
  note: 'Generated by scripts/sync-mappings.mjs. Edit data/overrides.json, not this file.',
  entries: [...rows.values()].sort((a, b) => a.package.localeCompare(b.package)),
};
if (!DRY) fs.writeFileSync(OUT, JSON.stringify(out, null, 2));

const withFeatures = out.entries.filter(e => e.feature_ids.length).length;
const swapCapable = out.entries.filter(e => e.feature_ids.length && e.usage_analyzed).length;
console.log(`module-replacements@${pkg.version}: ${considered} module mappings read`);
console.log(`${DRY ? 'dry-run: would write' : 'wrote'} ${out.entries.length} entries${DRY ? '' : ` -> ${OUT}`}`);
console.log(`  ${withFeatures} carry a Baseline feature id, ${swapCapable} also have usage analysis (can be reported as swap)`);
console.log(`  ${out.entries.length - withFeatures} have no Baseline feature and can only ever be "keep"`);
if (unresolvedFeatures.size) {
  console.log(`  ${unresolvedFeatures.size} feature ids are absent from the local web-features snapshot, skipped:`);
  console.log('   ', [...unresolvedFeatures].slice(0, 8).join(', '));
}
if (!out.entries.length) throw new Error('no mappings produced');
if (swapCapable < 20) throw new Error(`suspiciously few usage-analyzed rows: ${swapCapable}`);
